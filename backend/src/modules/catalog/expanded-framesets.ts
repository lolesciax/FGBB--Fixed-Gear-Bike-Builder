import {
  registeredFrameAssets,
  type Product,
  type Variant,
} from "@tracklab/domain";
import { checkedAt } from "./research-records";
type Specs = Variant["specs"];
type Row = [
  string,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
];
const limitations =
  "Original illustrative geometry at sourced attachment points. Tube cross-sections, welds, fork surfaces, dropouts, hardware and paint are approximate; no official graphics or manufacturer model is included. Missing interfaces remain unverified.";
function reviewed(
  id: string,
  brandId: string,
  brand: string,
  name: string,
  source: string,
  finish: string,
  color: string,
  common: Specs,
  rows: Row[],
  extraLimits = "",
): Product {
  const variants = rows.map(
    ([
      size,
      seatTube,
      headTube,
      headAngle,
      seatAngle,
      chainstay,
      bbDrop,
      stack,
      reach,
      wheelbase,
      effectiveTopTube,
    ]) => {
      const variantId = `${id}-${size.toLowerCase()}`;
      return {
        id: variantId,
        label: `${size} / ${finish}`,
        color,
        specs: {
          ...common,
          size,
          finish,
          colorApproximate: true,
          seatTube,
          headTube,
          headAngle,
          seatAngle,
          chainstay,
          bbDrop,
          stack,
          reach,
          wheelbase,
          effectiveTopTube,
        },
        ...(registeredFrameAssets.find((a) => a.variantId === variantId)
          ? {
              asset3D: registeredFrameAssets.find(
                (a) => a.variantId === variantId,
              ),
            }
          : {}),
      };
    },
  );
  return {
    id,
    brandId,
    brand,
    name,
    slot: "frameset",
    status: "published",
    catalogKind: "manufacturer",
    illustrative: false,
    source,
    verifiedAt: checkedAt,
    description: `${name}: reviewed ${finish} size variants with an approximate, dimension-based preview.`,
    acknowledgment: `${brand} names identify the product only. TrackLab is independent. ${limitations} ${extraLimits}`,
    visual: {
      assetId: "tracklab-parametric-v2",
      fidelity: "measurement-schematic",
      source: "TrackLab original independent geometry",
      license: "CC0-1.0",
      reviewedAt: checkedAt,
    },
    provenance: {
      reviewedAt: checkedAt,
      fields: [
        ...new Set(variants.flatMap((v) => Object.keys(v.specs))),
      ].filter((k) => !["colorApproximate"].includes(k)),
      limitations: `${limitations} ${extraLimits}`,
    },
    variants,
  };
}
