function draft(
  id: string,
  brandId: string,
  brand: string,
  name: string,
  source: string,
  variants: Product["variants"],
  notes: string,
): Product {
  return {
    id,
    brandId,
    brand,
    name,
    source,
    slot: "frameset",
    status: "draft",
    illustrative: false,
    catalogKind: "manufacturer",
    verifiedAt: checkedAt,
    description: notes,
    acknowledgment: `${brand} identification only; independent project. Rendering unavailable.`,
    provenance: {
      reviewedAt: checkedAt,
      fields: [...new Set(variants.flatMap((v) => Object.keys(v.specs)))],
      limitations: notes,
    },
    variants,
  };
}
