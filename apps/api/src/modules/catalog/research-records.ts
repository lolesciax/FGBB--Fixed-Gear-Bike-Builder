function model(
  brandId: string,
  id: string,
  name: string,
  source: string,
  notes: string,
  specificationStatus: ModelRecord["specificationStatus"] = "partial",
  productId?: string,
  revision?: string,
): ModelRecord {
  return modelRecordSchema.parse({
    id,
    brandId,
    name,
    source,
    checkedAt,
    notes,
    specificationStatus,
    ...(productId ? { productId } : {}),
    ...(revision ? { revision } : {}),
  });
}
